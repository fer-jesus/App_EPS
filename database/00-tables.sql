    REFERENCES HISTORIAL_CAMBIOS (id_cambios),
  CONSTRAINT fk_HISTORIAL_TASAS_TASAS1
    FOREIGN KEY (TASAS_id_tasa)
    REFERENCES TASAS (id_tasa)
);

-- Tabla: HISTORIAL_TASAS_TARIFA
CREATE TABLE HISTORIAL_TASAS_TARIFA (
  HISTORIAL_CAMBIOS_id_cambios INT NOT NULL,
  TASAS_TARIFA_TASAS_id_tasa INT NOT NULL,
  TASAS_TARIFA_tarifa_correlativo INT NOT NULL,
  TASAS_TARIFA_TARIFA_id_nombreTarifa INT NOT NULL,
  dimension_construccion DECIMAL NULL,
  formula VARCHAR(250) NOT NULL,
  valor DECIMAL NOT NULL,
   PRIMARY KEY (HISTORIAL_CAMBIOS_id_cambios, TASAS_TARIFA_TASAS_id_tasa, TASAS_TARIFA_tarifa_correlativo, TASAS_TARIFA_TARIFA_id_nombreTarifa),
  CONSTRAINT fk_HISTORIAL_TASAS_TARIFA_HISTORIAL_CAMBIOS1
    FOREIGN KEY (HISTORIAL_CAMBIOS_id_cambios)
    REFERENCES HISTORIAL_CAMBIOS (id_cambios),
  CONSTRAINT fk_HISTORIAL_TASAS_TARIFA_TASAS_TARIFA1
     FOREIGN KEY (TASAS_TARIFA_TASAS_id_tasa, TASAS_TARIFA_TARIFA_correlativo, TASAS_TARIFA_TARIFA_id_nombreTarifa)
     REFERENCES TASAS_TARIFA (TASAS_id_tasa, tarifa_correlativo, TARIFA_id_nombreTarifa)
);

-- Tabla: HISTORIAL_LICENCIAS
CREATE TABLE HISTORIAL_LICENCIAS (
  LICENCIAS_id_licencia INT NOT NULL,
  LICENCIAS_fecha_emisionL DATE NOT NULL,
  HISTORIAL_CAMBIOS_id_cambios INT NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  estado ENUM('PENDIENTE', 'ACTIVO', 'VENCIDO') NOT NULL,
  rotulo ENUM('50', '100', 'RAZONADO') NOT NULL,
  PRIMARY KEY (LICENCIAS_id_licencia, LICENCIAS_fecha_emisionL, HISTORIAL_CAMBIOS_id_cambios),
  CONSTRAINT fk_HISTORIAL_LICENCIAS_LICENCIAS1
    FOREIGN KEY (LICENCIAS_id_licencia, LICENCIAS_fecha_emisionL)
    REFERENCES LICENCIAS (id_licencia, fecha_emisionL),
  CONSTRAINT fk_HISTORIAL_LICENCIAS_HISTORIAL_CAMBIOS1
    FOREIGN KEY (HISTORIAL_CAMBIOS_id_cambios)
    REFERENCES HISTORIAL_CAMBIOS (id_cambios)
);

